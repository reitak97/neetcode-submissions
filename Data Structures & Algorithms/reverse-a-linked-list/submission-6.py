# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next

class Solution:
    def reverseList(self, head: Optional[ListNode]) -> Optional[ListNode]:
        curr = head
        prev = None
        while curr:
            #1
            tmp = curr.next
            curr.next = prev
            #0
            prev = curr

            #1
            curr = tmp

        return prev
